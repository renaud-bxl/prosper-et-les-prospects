const FOLD = { À: 'A', Â: 'A', Ä: 'A', È: 'E', Ê: 'E', Ë: 'E', Î: 'I', Ï: 'I', Ô: 'O', Ö: 'O', Ù: 'U', Û: 'U', Ü: 'U', Ç: 'C', Œ: 'O' };
const glyph = (ch) => GLYPHS[ch] ?? GLYPHS[FOLD[ch]] ?? GLYPHS[' '];

/** Largeur d'un texte, en pixels. */
export function textWidth(text) {
  let w = 0;
  for (const ch of String(text).toUpperCase()) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

/** Écrit un texte en pixels ; renvoie sa largeur. */
export function pixelText(g, text, x, y, color) {
  g.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of String(text).toUpperCase()) {
    const gl = glyph(ch);
    for (let r = 0; r < gl.length; r++) {
      const row = gl[r];
      for (let c = 0; c < row.length; c++) if (row[c] === '#') g.fillRect(cx + c, Math.round(y) + r, 1, 1);
    }
    cx += gl[0].length + 1;
  }
  return cx - Math.round(x) - 1;
}

