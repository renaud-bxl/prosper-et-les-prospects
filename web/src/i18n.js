export const LANGUAGES = ['fr', 'nl', 'en'];
let language = 'fr';
try { const saved = globalThis.localStorage?.getItem('prosper.lang'); if (LANGUAGES.includes(saved)) language = saved; } catch {}
export const getLang = () => language;
export const getLocale = () => ({ fr: 'fr-BE', nl: 'nl-BE', en: 'en-GB' })[language];
export function setLang(lang) {
  if (!LANGUAGES.includes(lang)) return;
  const changed = lang !== language;
  language = lang;
  try { globalThis.localStorage?.setItem('prosper.lang', lang); } catch {}
  if (globalThis.document) document.documentElement.lang = lang;
  if (changed && globalThis.location?.reload) globalThis.location.reload();
}

