const patterns = Object.entries(messages).filter(([key]) => /\{\w+\}/.test(key)).map(([key, values]) => {
  const names = [];
  const pattern = key.split(/(\{\w+\})/).map((part) => {
    if (/^\{\w+\}$/.test(part)) { names.push(part.slice(1, -1)); return '(.+?)'; }
    return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }).join('');
  return { key, values, names, regex: new RegExp('^' + pattern + '$') };
});

export function t(phrase, vars = {}) {
  const key = String(phrase ?? '');
  let template = key;
  let values = vars;
  if (language !== 'fr') {
    const index = language === 'nl' ? 0 : 1;
    if (messages[key]) template = messages[key][index];
    else {
      // Older stored missions include complete French system messages. Translate their fixed wording only.
      const match = patterns.map((entry) => ({ entry, found: entry.regex.exec(key) })).find((m) => m.found);
      if (match) {
        template = match.entry.values[index];
        values = { ...Object.fromEntries(match.entry.names.map((name, i) => [name, match.found[i + 1]])), ...vars };
      }
    }
  }
  return template.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name] ?? '') : token);
}
